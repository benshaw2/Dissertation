transform = transforms.Compose([transforms.ToTensor(), transforms.Normalize(mean=(-0.001,-0.001,-0.001), std=(1.001,1.001,1.001))]) #was mean -0.5 and std 1.0 at round 1.

target_transform_one_hot_f = transforms.Lambda(lambda y: F.one_hot(torch.tensor(y), num_classes=10).float())

batch_size = 512

